"""Import the Helios test-plan workbook into testplan/manifest.yaml.

    python tools/import_testplan.py "/path/to/Helios_ScaleUp_TestPlan-AMD.xlsx"

Sheets used: ``Testcases`` (master list: ID, level, title), ``afm`` and
``mortaro`` (status / suites / description). Duplicate or missing IDs in the
workbook get a stable canonical ID; the original is kept as ``plan_id``.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import openpyxl
import yaml

OUT = Path(__file__).resolve().parents[1] / "testplan" / "manifest.yaml"

# (plan id, title) -> canonical id. TC-AFM-005 and -048 are each used twice in the
# workbook; the afm suite sheet defines 005 = failover CRUD and 048 = techsupport.
RENAMES = {
    ("TC-AFM-005", "RCCL Cross Domain"): "TC-AFM-005A",
    ("TC-AFM-048", "Audit Events"): "TC-AFM-048A",
    ("", "Switch Decommision/Delete/Drain Not allowed in Minirack"): "TC-AFM-035A",
}

CATEGORIES = {  # longest prefix wins
    "TC-AFM-AGGW": "aggwatch", "TC-AFM-RC": "afm-reconfigure", "TC-AFM-LU": "afm-driver",
    "TC-AFM-UPGRADE": "afm-upgrade", "TC-AFM": "afm", "TC-BU": "sideband-bringup",
    "TC-BUG": "bug-regression", "TC-CTL": "controller", "TC-CTRL": "ifcp-version",
    "TC-E2E": "e2e-failover", "TC-EVT": "event-hub", "TC-HW": "hardware", "TC-MCH": "mch",
    "TC-NA": "node-agent", "TC-RAS-reset": "ras-reset", "TC-SBM": "sideband", "TC-SEQ": "sideband-sequence",
    "TC-STR": "stress", "TC-SWA": "switch-agent", "TC-SWH": "switch-hw", "TC-TRG": "ifcp-triggers",
    "TC-AR": "agent-restart", "TC-IBS": "scale-out-rdma", "TC": "ifcp-negotiation",
}


def category(tc: str) -> str:
    for prefix in sorted(CATEGORIES, key=len, reverse=True):
        if re.fullmatch(rf"{re.escape(prefix)}-\d+[A-Z]?", tc):
            return CATEGORIES[prefix]
    return "uncategorized"


def suite_rows(ws) -> list[dict]:
    rows, header = [], None
    for r in ws.iter_rows(values_only=True):
        if r and r[0] == "TC ID":
            header = r
            continue
        if header and r and r[0] and r[1] and str(r[1]).startswith("L"):
            rows.append(dict(zip(header, r)))
    return rows


def main(xlsx: str) -> None:
    wb = openpyxl.load_workbook(xlsx, data_only=True, read_only=True)
    suites: dict[str, dict] = {}
    slugs = []
    for sheet in ("afm", "mortaro"):
        if sheet not in wb.sheetnames:
            continue
        for r in suite_rows(wb[sheet]):
            tc = str(r["TC ID"]).strip()
            entry = {"level": r["Level"], "status": r.get("Status"), "bucket": r.get("Bucket"),
                     "suites": [s.strip() for s in str(r.get("Suites") or "").split(",") if s.strip() and s.strip() != "(unassigned)"],
                     "description": (r.get("Description") or "").strip()}
            if tc.startswith("TC-"):
                suites.setdefault(tc, entry)
            else:
                slugs.append({"slug": tc, **entry})

    cases, seen = [], set()
    for r in wb["Testcases"].iter_rows(min_row=2, values_only=True):
        plan_id = str(r[0] or "").strip()
        level, title = (r[1] or "").strip(), str(r[2] or "").strip()
        if not title:
            continue
        cid = RENAMES.get((plan_id, title), plan_id)
        if not cid or cid in seen:
            n = 2
            while f"{plan_id or 'TC-NOID'}-DUP{n}" in seen:
                n += 1
            cid = f"{plan_id or 'TC-NOID'}-DUP{n}"
        seen.add(cid)
        case = {"id": cid, "level": level, "title": title, "category": category(cid)}
        if cid != plan_id:
            case["plan_id"] = plan_id
        if cid in suites:
            case.update({k: v for k, v in suites[cid].items() if k in ("suites", "description") and v})
        cases.append(case)

    for tc, entry in suites.items():  # mortaro (scale-out) rows aren't in the Testcases sheet
        if tc not in seen:
            cases.append({"id": tc, "level": entry["level"], "title": entry["description"].split(" — ")[0][:80],
                          "category": category(tc), "suites": entry["suites"], "description": entry["description"]})
            seen.add(tc)

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        f"# generated by tools/import_testplan.py from {Path(xlsx).name} — re-run instead of hand-editing\n"
        + yaml.safe_dump({"cases": cases, "afm_suite_slugs": slugs}, sort_keys=False, width=140, allow_unicode=True))
    print(f"{len(cases)} cases ({sum('plan_id' in c for c in cases)} renumbered), {len(slugs)} afm-sheet slugs -> {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
